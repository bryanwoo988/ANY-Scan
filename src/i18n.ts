export const DICTS = { en, zh, ms } as const
export type Lang = keyof typeof DICTS

export const LANGS: { code: Lang; name: string }[] = [
  { code: 'en', name: 'English' },
  { code: 'zh', name: '简体中文' },
  { code: 'ms', name: 'Bahasa Melayu' },
]

export function detectLang(langs: readonly string[] = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : []): Lang {
  for (const l of langs) {
    const s = l.toLowerCase()
    if (s.startsWith('zh')) return 'zh'
    if (s.startsWith('ms') || s.startsWith('id')) return 'ms'
    if (s.startsWith('en')) return 'en'
  }
  return 'en'
}

export type TFn = (key: TKey, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): TFn {
  const d = DICTS[lang]
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    return s
  }
}
